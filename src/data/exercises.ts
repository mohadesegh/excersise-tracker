const stand = pose(arms(), legs());

/** One repetition with a realistic tempo: lower under control, brief pause, drive up, reset. */
const rep = (
	top: Pose,
	bottom: Pose,
	down = 1.3,
	hold = 0.25,
	up = 0.9,
	rest = 0.45,
): PoseAnim => ({
	frames: [top, bottom, bottom, top],
	beats: [down, hold, up, rest],
	dur: down + hold + up + rest,
});

/** Lying on the back, one knee drawn to the chest by the hand on that side, the other foot planted. */
const kneeHug = (side: "l" | "r"): Pose => {
	const up = { hf: 118, ha: 6, k: 125, sf: 25, sa: -10, e: 60 };
	const down = { hf: 55, ha: 8, k: 105, sf: 0, sa: 14, e: 0 };
	const [l, r] = side === "l" ? [up, down] : [down, up];
	return pose({
		rp: -90,
		lhf: l.hf,
		lha: l.ha,
		lk: l.k,
		lsf: l.sf,
		lsa: l.sa,
		le: l.e,
		rhf: r.hf,
		rha: r.ha,
		rk: r.k,
		rsf: r.sf,
		rsa: r.sa,
		re: r.e,
	});
};

